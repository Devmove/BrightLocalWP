const STRINGS: Record<Lang, Dict> = { pt, en };

/** Normaliza códigos como `pt-BR`/`en-US` para `pt`/`en`. */
export function resolveLanguage(input: unknown, fallback: Lang = 'pt'): Lang {
  if (typeof input !== 'string') return fallback;
  const code = input.trim().toLowerCase();
  if (code === 'pt' || code.startsWith('pt-') || code.startsWith('pt_')) return 'pt';
  if (code === 'en' || code.startsWith('en-') || code.startsWith('en_')) return 'en';
  return fallback;
}

export function translate(
  lang: Lang,
  key: string,
  vars: Record<string, string | number> = {},
): string {
  const template = STRINGS[lang]?.[key] ?? STRINGS.pt[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    name in vars ? String(vars[name]) : `{${name}}`,
  );
}
